/** The URL a bundled picture is served from; carries the site's base path, as the Fourier font does. */
export function pictureUrl(id: ImageId): string {
  return `${import.meta.env.BASE_URL}jpeg/${id}.png`;
}

/** The catalog entry for `id`. */
function entry(id: ImageId) {
  return IMAGES.find((im) => im.id === id);
}

/**
 * Load a gallery picture as pixels: a bundled one is fetched from the site and
 * decoded like an upload; a generated one comes from the kit. Rejects, with a
 * reader-facing message naming the picture, when a bundled file cannot be fetched.
 */
export async function loadPicture(id: ImageId): Promise<RgbaImage> {
  const im = entry(id);
  if (!im?.file) return loadBuiltin(id);
  const name = im.label;
  let res: Response;
  try {
    res = await fetch(pictureUrl(id));
  } catch {
    throw new Error(`Could not load the picture "${name}". Check your connection and try again.`);
  }
  if (!res.ok) throw new Error(`Could not load the picture "${name}" (the server answered ${res.status}).`);
  try {
    return await decodeUpload(await res.blob());
  } catch {
    // A wrong base path can answer 200 with the site's index page, and a file can be corrupt.
    throw new Error(`Could not load the picture "${name}" (the file is not a readable image).`);
  }
}

/**
 * A thumbnail `side` pixels square for the gallery: a bundled picture's own
 * file URL, or a PNG data URL for a generated one. The generated picture is
 * made at `BUILTIN_SIDE²`, the size the reader gets, because several generators
 * (text cells, 8 × 8 cosine blocks, the noise hash) do not scale with the size
 * asked for. Smooth pictures are then scaled down; fine patterns would alias to
 * a flat tint, so those show a 1:1 window cut from the centre instead.
 */
export function thumbnail(id: ImageId, side: number): Promise<string> {
  if (entry(id)?.file) return Promise.resolve(pictureUrl(id));
  // The overview is visited again and again; a generated thumbnail is made once per picture and size.
  const key = `${id}@${side}`;
  let made = thumbnails.get(key);
  if (!made) {
    made = drawThumbnail(id, side);
    thumbnails.set(key, made);
    made.catch(() => thumbnails.delete(key)); // a failure is not remembered: the next visit tries again
  }
  return made;
}

/** Generated thumbnails already made (or being made), by `id@side`. */
const thumbnails = new Map<string, Promise<string>>();

/** Draw the thumbnail `thumbnail` caches. */
async function drawThumbnail(id: ImageId, side: number): Promise<string> {
  const viz = await loadVizCore();
  const full = document.createElement('canvas');
  full.width = BUILTIN_SIDE;
  full.height = BUILTIN_SIDE;
  const fullCtx = full.getContext('2d');
  const canvas = document.createElement('canvas');
  canvas.width = side;
  canvas.height = side;
  const ctx = canvas.getContext('2d');
  if (!fullCtx || !ctx) throw new Error('This browser cannot draw thumbnails.');
  const pixels = fullCtx.createImageData(BUILTIN_SIDE, BUILTIN_SIDE);
  pixels.data.set(viz.jpeg_builtin_image(id, BUILTIN_SIDE, BUILTIN_SIDE));
  fullCtx.putImageData(pixels, 0, 0);
  if (entry(id)?.thumb === 'crop') {
    const from = Math.max(0, Math.floor((BUILTIN_SIDE - side) / 2));
    const span = Math.min(side, BUILTIN_SIDE);
    ctx.drawImage(full, from, from, span, span, 0, 0, side, side);
  } else {
    ctx.imageSmoothingEnabled = true;
    ctx.imageSmoothingQuality = 'high';
    ctx.drawImage(full, 0, 0, side, side);
  }
  return canvas.toDataURL('image/png');
}

/** A generated built-in at `BUILTIN_SIDE²`. */
export async function loadBuiltin(id: ImageId): Promise<RgbaImage> {
  const viz = await loadVizCore();
  return { w: BUILTIN_SIDE, h: BUILTIN_SIDE, rgba: viz.jpeg_builtin_image(id, BUILTIN_SIDE, BUILTIN_SIDE) };
}

/** The size an `w × h` upload is scaled to: unchanged when it fits, else shrunk to fit `max` keeping its shape. */
export function fitWithin(w: number, h: number, max = MAX_SIDE): { w: number; h: number } {
  if (!(w > 0 && h > 0)) return { w: 0, h: 0 };
  const s = Math.min(1, max / Math.max(w, h));
  return { w: Math.max(1, Math.round(w * s)), h: Math.max(1, Math.round(h * s)) };
}

/**
 * Decode an uploaded file with the browser and scale it to fit `MAX_SIDE`.
 * Rejects (with a reader-facing message) when the file is not an image the
 * browser can open.
 */
export async function decodeUpload(file: Blob): Promise<RgbaImage> {
  let bitmap: ImageBitmap;
  try {
    bitmap = await createImageBitmap(file);
  } catch {
    throw new Error('That file is not an image this browser can open.');
  }
  const { w, h } = fitWithin(bitmap.width, bitmap.height);
  const canvas = document.createElement('canvas');
  canvas.width = w;
  canvas.height = h;
  const ctx = canvas.getContext('2d', { willReadFrequently: true });
  if (!ctx) {
    bitmap.close();
    throw new Error('This browser cannot read image pixels.');
  }
  // JPEG has no alpha: paint white first so transparent areas are not black.
  ctx.fillStyle = '#fff';
  ctx.fillRect(0, 0, w, h);
  ctx.drawImage(bitmap, 0, 0, w, h);
  bitmap.close();
  const data = ctx.getImageData(0, 0, w, h).data;
  return { w, h, rgba: new Uint8Array(data.buffer, data.byteOffset, data.byteLength) };
}
